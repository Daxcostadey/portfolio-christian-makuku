(function () {
  var SUPPORTED = ["fr", "en", "sw"];
  var STORAGE_KEY = "cmv-lang";

  function detect() {
    var param = new URLSearchParams(location.search).get("lang");
    if (param && SUPPORTED.indexOf(param) !== -1) return param;
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;
    } catch (e) {}
    var prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ""];
    for (var i = 0; i < prefs.length; i++) {
      var code = String(prefs[i]).toLowerCase().slice(0, 2);
      if (SUPPORTED.indexOf(code) !== -1) return code;
    }
    return "en";
  }

  var DEFAULT_NAME = "Christian Makuku Valentin";

  function t(key, lang) {
    lang = lang || window.currentLang;
    var custom = (window.I18N_OVERRIDES || {})[lang] || {};
    var dict = window.I18N[lang] || {};
    var value = custom[key] != null ? custom[key]
      : dict[key] != null ? dict[key]
      : (window.I18N.fr[key] != null ? window.I18N.fr[key] : null);
    if (value != null && window.SITE_NAME && window.SITE_NAME !== DEFAULT_NAME) {
      value = value.split(DEFAULT_NAME).join(window.SITE_NAME);
    }
    return value;
  }

  function apply(lang) {
    window.currentLang = lang;
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n"), lang);
      if (value != null) el.textContent = value;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n-aria"), lang);
      if (value != null) el.setAttribute("aria-label", value);
    });
    document.querySelectorAll(".lang-switch button").forEach(function (b) {
      var on = b.getAttribute("data-lang") === lang;
      b.classList.toggle("active", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  function setLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    apply(lang);
  }

  window.t = t;
  window.setLang = setLang;
  window.applyLang = apply;

  document.addEventListener("click", function (e) {
    var btn = e.target.closest(".lang-switch button");
    if (btn) setLang(btn.getAttribute("data-lang"));
  });

  apply(detect());
})();
